import gradio as gr
import pandas as pd
import plotly.express as px
import io

def process_excel(file):
    if file is None:
        return "Please upload an Excel file!", None, None

    # Excel file ko read karna
    df = pd.read_excel(file.name)

    # Basic info
    total_rows = len(df)
    columns = list(df.columns)

    # Agar numeric columns hain toh summary statistics
    summary = df.describe().to_html()

    # Plotly chart banana (agar numeric data hai)
    chart_html = None
    numeric_cols = df.select_dtypes(include=['number']).columns

    if len(numeric_cols) >= 2:
        fig = px.bar(df, x=df.columns[0], y=numeric_cols[0],
                     title=f"{numeric_cols[0]} by {df.columns[0]}",
                     template="plotly_white")
        chart_html = fig.to_html(full_html=False)

    # Data table
    table_html = df.to_html(index=False, classes="table table-striped")

    return f"✅ Successfully processed {total_rows} rows!", chart_html, table_html

# Gradio Interface banana
with gr.Blocks(theme=gr.themes.Soft()) as demo:
    gr.Markdown("# 📊 Smart Excel Dashboard")
    gr.Markdown("Upload your Excel file and get instant insights with interactive charts!")

    with gr.Row():
        with gr.Column():
            file_input = gr.File(label="Upload Excel File (.xlsx)", file_types=[".xlsx"])
            upload_btn = gr.Button("Process Data", variant="primary")

        with gr.Column():
            status_output = gr.Textbox(label="Status")

    chart_output = gr.HTML(label="📈 Interactive Chart")
    table_output = gr.HTML(label="📋 Data Table")

    upload_btn.click(
        fn=process_excel,
        inputs=[file_input],
        outputs=[status_output, chart_output, table_output]
    )

# Launch karna with share link
demo.launch(share=True, inline=False)